package com.helpdesk.ticket.domain;

import com.helpdesk.common.error.ApiException;
import com.helpdesk.common.error.ErrorCode;
import com.helpdesk.common.persistence.TenantOwnedEntity;
import com.helpdesk.user.User;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import java.time.Instant;
import java.util.Objects;
import java.util.UUID;
import org.springframework.data.annotation.LastModifiedDate;

/**
 * The aggregate root. Invariants live here (not in controllers). Comments and history are
 * deliberately <em>not</em> mapped as collections — each is read through its own paginated query.
 */
@Entity
@Table(name = "tickets")
public class Ticket extends TenantOwnedEntity {

    @Column(nullable = false, updatable = false)
    private Long number;

    @Column(nullable = false, length = 200)
    private String subject;

    @Column(nullable = false, columnDefinition = "text")
    private String description;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 10)
    private TicketPriority priority;

    /** Generated by PostgreSQL from {@code priority}; read-only, used to sort in business order. */
    @Column(name = "priority_rank", insertable = false, updatable = false)
    private Short priorityRank;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 15)
    private TicketStatus status;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "requester_id", nullable = false, updatable = false)
    private User requester;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "assignee_id")
    private User assignee;

    @Column(name = "resolved_at")
    private Instant resolvedAt;

    @Column(name = "closed_at")
    private Instant closedAt;

    @Version
    @Column(nullable = false)
    private Long version;

    @LastModifiedDate
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected Ticket() {
    }

    private Ticket(UUID organizationId, long number, String subject, String description,
                   TicketPriority priority, User requester) {
        super(organizationId);
        this.number = number;
        this.subject = subject;
        this.description = description;
        this.priority = priority;
        this.status = TicketStatus.OPEN;
        this.requester = requester;
    }

    /** A new OPEN ticket. The requester must belong to the same organization. */
    public static Ticket open(UUID organizationId, long number, String subject, String description,
                              TicketPriority priority, User requester) {
        requireSameOrg(organizationId, requester);
        return new Ticket(organizationId, number, subject, description,
                priority == null ? TicketPriority.MEDIUM : priority, requester);
    }

    // ───────────── behaviour ─────────────

    /**
     * Applies a status change and its side effects (BR-5). The transition itself must already be
     * validated by {@link TicketStateMachine#validate}.
     */
    public void changeStatus(TicketStatus target, Instant now) {
        if (!TicketStateMachine.exists(status, target)) {
            throw new ApiException(ErrorCode.INVALID_STATUS_TRANSITION,
                    "Cannot change status from " + status + " to " + target);
        }
        switch (target) {
            case RESOLVED -> resolvedAt = now;
            case CLOSED -> {
                closedAt = now;
                if (resolvedAt == null) {
                    resolvedAt = now;
                }
            }
            case OPEN -> {
                resolvedAt = null;
                closedAt = null;
            }
            default -> {
                // IN_PROGRESS / ON_HOLD: no timestamps change
            }
        }
        this.status = target;
    }

    /** Assigns to an active AGENT or ORG_ADMIN of the same organization. */
    public void assignTo(User agent) {
        ensureNotClosed();
        requireSameOrg(getOrganizationId(), agent);
        if (!agent.isAssignable()) {
            throw new ApiException(ErrorCode.INVALID_ASSIGNEE, "Tickets can only be assigned to active agents or admins");
        }
        this.assignee = agent;
    }

    public void unassign() {
        ensureNotClosed();
        this.assignee = null;
    }

    /** Applies non-null fields. Field-level permission checks are done by {@link TicketAccessPolicy}. */
    public void updateDetails(String newSubject, String newDescription, TicketPriority newPriority) {
        ensureNotClosed();
        if (newSubject != null) {
            this.subject = newSubject;
        }
        if (newDescription != null) {
            this.description = newDescription;
        }
        if (newPriority != null) {
            this.priority = newPriority;
        }
    }

    /** BR-6: a CLOSED ticket is read-only until it is reopened. */
    public void ensureNotClosed() {
        if (isClosed()) {
            throw new ApiException(ErrorCode.TICKET_CLOSED, "Ticket #" + number + " is closed. Reopen it first");
        }
    }

    public boolean isClosed() {
        return status == TicketStatus.CLOSED;
    }

    public boolean isRequestedBy(UUID userId) {
        return requester.getId().equals(userId);
    }

    public UUID assigneeId() {
        return assignee == null ? null : assignee.getId();
    }

    private static void requireSameOrg(UUID organizationId, User user) {
        Objects.requireNonNull(user, "user");
        if (!user.belongsTo(organizationId)) {
            // Defense in depth: services already look users up within the org, and the DB has composite FKs.
            throw new IllegalArgumentException("User belongs to a different organization");
        }
    }

    // ───────────── getters ─────────────

    public Long getNumber() {
        return number;
    }

    public String getSubject() {
        return subject;
    }

    public String getDescription() {
        return description;
    }

    public TicketPriority getPriority() {
        return priority;
    }

    public Short getPriorityRank() {
        return priorityRank;
    }

    public TicketStatus getStatus() {
        return status;
    }

    public User getRequester() {
        return requester;
    }

    public User getAssignee() {
        return assignee;
    }

    public Instant getResolvedAt() {
        return resolvedAt;
    }

    public Instant getClosedAt() {
        return closedAt;
    }

    public Long getVersion() {
        return version;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }
}
